import React, { useEffect, useState } from "react";
import { useLabStore } from "@/store/labStore";
import { loopbackService } from "@/services/loopback.service";
import { Button } from "@/components/ui/button";
import { motion, useReducedMotion } from "motion/react";

export const BeginnerLab: React.FC = () => {
  const {
    currentStep,
    setStep,
    isPaused,
    setIsPaused,
    mailbox,
    gatheredCandidates,
    sdpOffer,
    sdpAnswer,
    dataChannelMessages,
    peerAConnectionState,
    peerBConnectionState,
  } = useLabStore();

  const [messageInputA, setMessageInputA] = useState("");
  const [messageInputB, setMessageInputB] = useState("");
  const [animatingPacket, setAnimatingPacket] = useState<string | null>(null);
  const shouldReduceMotion = useReducedMotion();

  useEffect(() => {
    // Initialize loopback service on mount
    loopbackService.init();

    // Expose for automated E2E tests
    if (typeof window !== "undefined") {
      (window as unknown as { __LOOPBACK_SERVICE__: typeof loopbackService }).__LOOPBACK_SERVICE__ = loopbackService;
    }

    return () => {
      loopbackService.reset();
    };
  }, []);

  const handleStartHandshake = async () => {
    setAnimatingPacket("Offer generated by Peer A");
    setTimeout(() => setAnimatingPacket(null), 1200);
    await loopbackService.startOfferFlow();
  };

  const handleStepMessage = async () => {
    if (mailbox.length > 0) {
      const head = mailbox[0];
      setAnimatingPacket(`${head.type.toUpperCase()} moving from Peer ${head.from} ➔ Peer ${head.to}`);
      setTimeout(() => setAnimatingPacket(null), 1200);
    }
    await loopbackService.stepNext();
  };

  const handleSendA = () => {
    if (!messageInputA.trim()) return;
    loopbackService.sendMessage("A", messageInputA.trim());
    setMessageInputA("");
  };

  const handleSendB = () => {
    if (!messageInputB.trim()) return;
    loopbackService.sendMessage("B", messageInputB.trim());
    setMessageInputB("");
  };

  const stepTitles = [
    "The Matchmaker (Signaling)",
    "The Business Card (SDP Offer / Answer)",
    "Finding the Path (ICE Candidates)",
  ];

  const whatHappenedTexts = [
    "WebRTC is peer-to-peer, but peers don't know where each other live yet. The signaling server acts as a matchmaker to swap initial contact info. In this lab, the matchmaker is simulated as an in-memory queue.",
    "Peer A creates an SDP offer listing its supported media codecs, protocols, and network capabilities. Candidates are gathered after setLocalDescription, and only for a media section or data channel in the offer. This lab adds a data channel before creating the offer so there is something to connect.",
    "Peers ping STUN servers to discover their public IP and test LAN routes. Each discovered route is packaged as an ICE candidate and trickled to the peer. Once a working pair is agreed upon, the peer-to-peer connection is established.",
  ];

  return (
    <div className="min-h-screen bg-slate-950 text-slate-100 flex flex-col p-4 md:p-8 font-sans selection:bg-cyan-500/30">
      {/* Header & Stepper Progress */}
      <header className="border-b border-slate-800 pb-4 mb-6">
        <div className="flex flex-col md:flex-row md:items-center justify-between gap-4">
          <div>
            <div className="flex items-center gap-2">
              <span className="text-xl font-bold tracking-tight text-cyan-400">WebRTC Learning Lab</span>
              <span className="px-2 py-0.5 text-xs font-mono font-semibold rounded bg-amber-500/10 text-amber-400 border border-amber-500/20">
                Beginner Guide
              </span>
            </div>
            <p className="text-xs text-slate-400 mt-1 font-mono">
              Step {currentStep} of 3: {stepTitles[currentStep - 1]}
            </p>
          </div>

          {/* Stepper Controls */}
          <div className="flex items-center gap-2 flex-wrap">
            <Button
              variant="outline"
              size="sm"
              disabled={currentStep <= 1}
              onClick={() => setStep(currentStep - 1)}
              data-testid="btn-back"
            >
              &larr; Back
            </Button>

            <Button
              variant="outline"
              size="sm"
              disabled={currentStep >= 3}
              onClick={() => setStep(currentStep + 1)}
              data-testid="btn-next"
            >
              Next Step &rarr;
            </Button>

            <Button
              variant={isPaused ? "secondary" : "outline"}
              size="sm"
              onClick={() => setIsPaused(!isPaused)}
              data-testid="btn-pause-toggle"
            >
              {isPaused ? "⏸️ Paused (Mailbox Gating)" : "▶️ Real-Time Delivery"}
            </Button>

            <Button
              variant="outline"
              size="sm"
              onClick={() => loopbackService.reset()}
              data-testid="btn-reset"
              className="text-rose-400 hover:text-rose-300"
            >
              Reset Lab
            </Button>
          </div>
        </div>

        {/* Progress Bar */}
        <div className="w-full bg-slate-900 h-1.5 rounded-full mt-4 overflow-hidden border border-slate-800">
          <div
            className="bg-cyan-500 h-full transition-all duration-300"
            style={{ width: `${(currentStep / 3) * 100}%` }}
          />
        </div>
      </header>

      {/* Main Interactive Stage */}
      <main className="flex-1 grid grid-cols-1 lg:grid-cols-3 gap-6 items-start">
        {/* PEER A */}
        <section className="bg-slate-900/80 border border-slate-800 rounded-xl p-4 flex flex-col gap-4">
          <div className="flex items-center justify-between border-b border-slate-800 pb-2">
            <div>
              <h2 className="font-bold text-slate-100 flex items-center gap-2">
                Peer A <span className="text-xs font-mono text-slate-400">(Caller)</span>
              </h2>
            </div>
            <span
              data-testid="peer-a-state"
              className={`px-2 py-0.5 rounded text-xs font-mono font-medium ${
                peerAConnectionState === "connected"
                  ? "bg-emerald-500/10 text-emerald-400 border border-emerald-500/20"
                  : "bg-slate-800 text-slate-400"
              }`}
            >
              {peerAConnectionState}
            </span>
          </div>

          {currentStep === 1 && (
            <div className="space-y-3">
              <p className="text-xs text-slate-400">
                Peer A is ready to initiate contact. Click below to create an SDP Offer.
              </p>
              <Button
                size="sm"
                className="w-full"
                onClick={handleStartHandshake}
                data-testid="btn-start-offer"
              >
                1. Create Offer &amp; Data Channel
              </Button>
            </div>
          )}

          {currentStep >= 2 && (
            <div className="space-y-2">
              <span className="text-xs uppercase font-semibold text-slate-500 font-mono">Local SDP Offer</span>
              {sdpOffer ? (
                <details className="text-xs bg-slate-950 p-2 rounded border border-slate-800/80 cursor-pointer">
                  <summary className="font-mono text-cyan-400 font-medium">Show raw SDP offer ({sdpOffer.length} chars)</summary>
                  <pre className="mt-2 text-[10px] text-slate-300 overflow-x-auto whitespace-pre font-mono p-2 bg-slate-900 rounded max-h-48 overflow-y-auto">
                    {sdpOffer}
                  </pre>
                </details>
              ) : (
                <p className="text-xs text-slate-500 italic">No offer created yet</p>
              )}
            </div>
          )}

          {/* Data Channel Messaging */}
          <div className="border-t border-slate-800 pt-3 mt-auto">
            <span className="text-xs uppercase font-semibold text-slate-500 font-mono block mb-2">
              Peer A Data Channel
            </span>
            <div className="flex gap-2">
              <input
                type="text"
                placeholder="Message to Peer B..."
                value={messageInputA}
                onChange={(e) => setMessageInputA(e.target.value)}
                onKeyDown={(e) => e.key === "Enter" && handleSendA()}
                className="bg-slate-950 border border-slate-800 text-xs rounded px-2.5 py-1.5 flex-1 font-mono focus:border-cyan-500 outline-none"
                data-testid="input-msg-a"
              />
              <Button size="sm" onClick={handleSendA} data-testid="btn-send-a">
                Send
              </Button>
            </div>
          </div>
        </section>

        {/* SIMULATED MAILBOX (MIDDLE) */}
        <section className="bg-slate-900/60 border border-slate-800 rounded-xl p-4 flex flex-col gap-4">
          <div className="flex items-center justify-between border-b border-slate-800 pb-2">
            <div className="flex items-center gap-2">
              <h2 className="font-bold text-slate-100">Signaling Channel</h2>
              <span className="text-[10px] font-mono px-1.5 py-0.5 rounded bg-amber-500/10 text-amber-400 border border-amber-500/20">
                [SIMULATION: In-Memory Mailbox]
              </span>
            </div>
            <span className="text-xs font-mono text-slate-400">
              {mailbox.length} in queue
            </span>
          </div>

          <p className="text-xs text-slate-400 leading-relaxed">
            In production, messages travel over WebSockets. Here, the in-memory mailbox holds messages so you can inspect each transfer.
          </p>

          {/* Mailbox Controls */}
          <div className="flex items-center gap-2">
            <Button
              size="sm"
              variant="default"
              disabled={mailbox.length === 0}
              onClick={handleStepMessage}
              className="flex-1 bg-cyan-600 hover:bg-cyan-500 text-white"
              data-testid="btn-step-msg"
            >
              Step Single Message ({mailbox.length}) &rarr;
            </Button>
          </div>

          {/* Packet Travel Animation */}
          {animatingPacket && (
            <motion.div
              initial={shouldReduceMotion ? { opacity: 0 } : { scale: 0.8, y: -5 }}
              animate={shouldReduceMotion ? { opacity: 1 } : { scale: 1, y: 0 }}
              className="p-2.5 rounded bg-cyan-950/60 border border-cyan-500/40 text-cyan-300 text-xs font-mono text-center"
            >
              🚀 {animatingPacket}
            </motion.div>
          )}

          {/* Mailbox Queue List */}
          <div className="space-y-2 max-h-48 overflow-y-auto">
            {mailbox.length === 0 ? (
              <div className="p-4 border border-dashed border-slate-800 rounded text-center text-xs text-slate-500 font-mono">
                Mailbox queue is empty
              </div>
            ) : (
              mailbox.map((m, idx) => (
                <div
                  key={m.id}
                  className="p-2 rounded bg-slate-950 border border-slate-800 text-xs font-mono flex items-center justify-between"
                >
                  <span className="font-semibold text-cyan-400">
                    #{idx + 1} {m.type.toUpperCase()}
                  </span>
                  <span className="text-slate-400">
                    Peer {m.from} &rarr; Peer {m.to}
                  </span>
                </div>
              ))
            )}
          </div>

          {/* Data Channel Activity */}
          <div className="border-t border-slate-800 pt-3 mt-auto">
            <span className="text-xs uppercase font-semibold text-slate-500 font-mono block mb-2">
              Data Channel Log
            </span>
            <div className="bg-slate-950 rounded border border-slate-800 p-2 max-h-28 overflow-y-auto font-mono text-[11px] space-y-1" data-testid="dc-log">
              {dataChannelMessages.length === 0 ? (
                <p className="text-slate-600 italic">No data channel messages yet</p>
              ) : (
                dataChannelMessages.map((msg, i) => (
                  <p key={i}>
                    <span className={msg.from === "A" ? "text-cyan-400 font-bold" : "text-emerald-400 font-bold"}>
                      Peer {msg.from}:
                    </span>{" "}
                    <span className="text-slate-300">{msg.text}</span>
                  </p>
                ))
              )}
            </div>
          </div>
        </section>

        {/* PEER B */}
        <section className="bg-slate-900/80 border border-slate-800 rounded-xl p-4 flex flex-col gap-4">
          <div className="flex items-center justify-between border-b border-slate-800 pb-2">
            <div>
              <h2 className="font-bold text-slate-100 flex items-center gap-2">
                Peer B <span className="text-xs font-mono text-slate-400">(Callee)</span>
              </h2>
            </div>
            <span
              data-testid="peer-b-state"
              className={`px-2 py-0.5 rounded text-xs font-mono font-medium ${
                peerBConnectionState === "connected"
                  ? "bg-emerald-500/10 text-emerald-400 border border-emerald-500/20"
                  : "bg-slate-800 text-slate-400"
              }`}
            >
              {peerBConnectionState}
            </span>
          </div>

          {currentStep >= 2 && (
            <div className="space-y-2">
              <span className="text-xs uppercase font-semibold text-slate-500 font-mono">Local SDP Answer</span>
              {sdpAnswer ? (
                <details className="text-xs bg-slate-950 p-2 rounded border border-slate-800/80 cursor-pointer">
                  <summary className="font-mono text-emerald-400 font-medium">Show raw SDP answer ({sdpAnswer.length} chars)</summary>
                  <pre className="mt-2 text-[10px] text-slate-300 overflow-x-auto whitespace-pre font-mono p-2 bg-slate-900 rounded max-h-48 overflow-y-auto">
                    {sdpAnswer}
                  </pre>
                </details>
              ) : (
                <p className="text-xs text-slate-500 italic">No answer generated yet</p>
              )}
            </div>
          )}

          {/* Data Channel Messaging */}
          <div className="border-t border-slate-800 pt-3 mt-auto">
            <span className="text-xs uppercase font-semibold text-slate-500 font-mono block mb-2">
              Peer B Data Channel
            </span>
            <div className="flex gap-2">
              <input
                type="text"
                placeholder="Message to Peer A..."
                value={messageInputB}
                onChange={(e) => setMessageInputB(e.target.value)}
                onKeyDown={(e) => e.key === "Enter" && handleSendB()}
                className="bg-slate-950 border border-slate-800 text-xs rounded px-2.5 py-1.5 flex-1 font-mono focus:border-emerald-500 outline-none"
                data-testid="input-msg-b"
              />
              <Button size="sm" onClick={handleSendB} data-testid="btn-send-b">
                Send
              </Button>
            </div>
          </div>
        </section>
      </main>

      {/* Step 3: GATHERED CANDIDATES MATRIX */}
      {currentStep >= 3 && (
        <section className="mt-6 bg-slate-900/60 border border-slate-800 rounded-xl p-4">
          <div className="flex items-center justify-between mb-3 border-b border-slate-800 pb-2">
            <h3 className="font-bold text-sm text-slate-200">
              Gathered ICE Candidates ({gatheredCandidates.length})
            </h3>
            <span className="text-xs font-mono text-slate-400">
              host = LAN &bull; srflx = STUN &bull; relay = TURN
            </span>
          </div>

          {gatheredCandidates.length === 0 ? (
            <p className="text-xs text-slate-500 italic font-mono py-2">
              No candidates gathered yet. Ensure SDP handshake has begun.
            </p>
          ) : (
            <div className="grid grid-cols-1 md:grid-cols-2 lg:grid-cols-3 gap-3">
              {gatheredCandidates.map((c) => (
                <div
                  key={c.id}
                  className="bg-slate-950 border border-slate-800 p-2.5 rounded-lg text-xs font-mono space-y-1"
                >
                  <div className="flex items-center justify-between">
                    <span className="font-bold text-slate-300">Peer {c.peer}</span>
                    <span
                      className={`px-1.5 py-0.5 rounded text-[10px] font-bold uppercase ${
                        c.type === "host"
                          ? "bg-emerald-500/10 text-emerald-400 border border-emerald-500/20"
                          : c.type === "srflx"
                          ? "bg-cyan-500/10 text-cyan-400 border border-cyan-500/20"
                          : "bg-purple-500/10 text-purple-400 border border-purple-500/20"
                      }`}
                    >
                      {c.type}
                    </span>
                  </div>
                  <p className="text-slate-400 text-[11px] truncate">
                    {c.address}:{c.port} ({c.protocol.toUpperCase()})
                  </p>
                  {c.isMdns && (
                    <p className="text-[10px] text-amber-400/90 bg-amber-500/5 p-1 rounded border border-amber-500/10">
                      ℹ️ mDNS Privacy (RFC 8837): Browser masks local IP to protect user identity.
                    </p>
                  )}
                </div>
              ))}
            </div>
          )}
        </section>
      )}

      {/* "What Just Happened?" Explainer Drawer */}
      <footer className="mt-6 bg-slate-900 border border-slate-800 rounded-xl p-4">
        <div className="flex items-center gap-2 mb-2">
          <span className="text-amber-400 text-sm">💡</span>
          <h3 className="font-bold text-sm text-slate-200">What Just Happened?</h3>
        </div>
        <p className="text-xs text-slate-300 leading-relaxed">
          {whatHappenedTexts[currentStep - 1]}
        </p>
      </footer>
    </div>
  );
};
